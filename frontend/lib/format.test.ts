import { money, pluralRu } from "./format";

test("formats millions of rubles", () => {
  expect(money(18500000)).toBe("18.5 млн ₽");
  expect(money(21000000)).toBe("21 млн ₽");
});

it("не выдумывает цену, когда её нет", () => {
  // Go шлёт *int64 и присылает null; раньше money(null) рисовал «0 млн ₽»
  expect(money(null)).toBe("цена не указана");
  expect(money(undefined)).toBe("цена не указана");
  expect(money(44872500)).toBe("44.9 млн ₽");
});

describe("pluralRu", () => {
  it("даёт форму «одна» только для чисел, оканчивающихся на 1 (кроме 11)", () => {
    expect(pluralRu(1, "станция", "станции", "станций")).toBe("станция");
    expect(pluralRu(21, "станция", "станции", "станций")).toBe("станция");
    expect(pluralRu(11, "станция", "станции", "станций")).toBe("станций");
  });

  it("даёт форму «несколько» для 2-4 (кроме 12-14)", () => {
    expect(pluralRu(2, "станция", "станции", "станций")).toBe("станции");
    expect(pluralRu(3, "станция", "станции", "станций")).toBe("станции");
    expect(pluralRu(4, "станция", "станции", "станций")).toBe("станции");
    expect(pluralRu(12, "станция", "станции", "станций")).toBe("станций");
    expect(pluralRu(14, "станция", "станции", "станций")).toBe("станций");
  });

  it("даёт форму «много» для 0, 5-20 и большинства остальных", () => {
    expect(pluralRu(0, "станция", "станции", "станций")).toBe("станций");
    expect(pluralRu(5, "станция", "станции", "станций")).toBe("станций");
    expect(pluralRu(6, "станция", "станции", "станций")).toBe("станций");
    expect(pluralRu(20, "станция", "станции", "станций")).toBe("станций");
  });
});
